/*
 * Adds cross-origin isolation headers (COOP/COEP) to same-origin responses so expo-sqlite's
 * WebAssembly worker can use SharedArrayBuffer on hosts that can't set response headers
 * (including the Expo dev server, which serves its HTML before Metro middleware runs).
 * Production hosting should send these headers itself; this is a fallback.
 */
self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', (event) => event.waitUntil(self.clients.claim()));

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.cache === 'only-if-cached' && request.mode !== 'same-origin') return;
  if (new URL(request.url).origin !== self.location.origin) return;

  event.respondWith(
    fetch(request).then((response) => {
      if (response.status === 0) return response;
      const headers = new Headers(response.headers);
      headers.set('Cross-Origin-Embedder-Policy', 'credentialless');
      headers.set('Cross-Origin-Opener-Policy', 'same-origin');
      return new Response(response.body, { status: response.status, statusText: response.statusText, headers });
    }),
  );
});
