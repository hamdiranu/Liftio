#!/usr/bin/env node
/**
 * Scans assets/images/exercises and assets/images/gym and writes
 * src/constants/image-manifest.ts with static require() calls (Metro needs them static).
 *
 *   assets/images/exercises/<exercise-slug>.(jpg|jpeg|png|webp)
 *   assets/images/gym/<name>.(jpg|jpeg|png|webp)      e.g. hero.jpg, coach.jpg, profile.jpg
 *
 * Run with `npm run generate:images` after adding or removing photos.
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const exts = new Set(['.jpg', '.jpeg', '.png', '.webp']);

function scan(dir) {
  const abs = path.join(root, 'assets', 'images', dir);
  if (!fs.existsSync(abs)) return [];
  return fs
    .readdirSync(abs)
    .filter((f) => exts.has(path.extname(f).toLowerCase()))
    .sort()
    .map((f) => ({ key: path.basename(f, path.extname(f)), file: `@/assets/images/${dir}/${f}` }));
}

const entries = (items) => items.map((i) => `  '${i.key}': require('${i.file}'),`).join('\n');

const exercises = scan('exercises');
const gym = scan('gym');

const out = `// Generated by scripts/generate-image-manifest.js — do not edit by hand.

export const EXERCISE_IMAGES: Record<string, number> = {
${entries(exercises)}
};

export const GYM_IMAGES: Record<string, number> = {
${entries(gym)}
};
`;

fs.writeFileSync(path.join(root, 'src', 'constants', 'image-manifest.ts'), out);
console.log(`Image manifest: ${exercises.length} exercise photos, ${gym.length} gym photos.`);
